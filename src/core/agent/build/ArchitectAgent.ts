/**
 * ArchitectAgent handles technical architecture and planning
 * Generates task lists, steering documents, and tech recommendations
 */
export class ArchitectAgent extends BaseAgent {
    private readonly temperature: number;
    private readonly projectContext: string;

    constructor(
        config: Omit<BaseAgentConfig, 'agentType'>,
        options: ArchitectAgentOptions = {}
    ) {
        super({
            ...config,
            agentType: 'architect' as any, // Will be added to AgentType
            mode: config.mode || 'build',
        });

        // Use lower temperature for consistent, deterministic output
        this.temperature = options.temperature ?? 0.3;
        this.projectContext = options.projectContext || '';
    }

    /**
     * Register capabilities for architect agent
     */
    protected registerCapabilities(): void {
        this.capabilityRegistry.register(
            this.conversationId,
            TECHNICAL_ARCHITECTURE
        );
        // Also register summarization for dependency analysis
        this.capabilityRegistry.register(
            this.conversationId,
            AGENT_CAPABILITIES.SUMMARIZATION
        );
    }

    /**
     * Get system prompt for architect agent
     * Returns technical architecture prompt
     */
    public getSystemPrompt(): string {
        return `You are a solutions architect specializing in software development planning.

Your expertise includes:
- Breaking down user stories into implementable tasks
- Analyzing task dependencies and identifying critical paths
- Recommending technology stacks and architectural patterns
- Creating coding standards and quality guidelines
- Estimating development effort and complexity

${this.projectContext ? `Project Context:\n${this.projectContext}\n` : ''}

Guidelines:
- Be specific and actionable in your recommendations
- Consider maintainability, scalability, and testability
- Prioritize industry best practices
- Account for real-world constraints (time, budget, team size)
- Provide rationale for technical decisions

Output Format:
- Always provide structured JSON output when requested
- Use consistent naming conventions
- Include clear descriptions and acceptance criteria`;
    }

    /**
     * Get the configured temperature for this agent
     */
    public getTemperature(): number {
        return this.temperature;
    }

    /**
     * Generate implementation tasks from stories and pages
     *
     * @param stories - User stories (JSON string or object array)
     * @param pages - Page designs (JSON string or object array)
     * @returns Task generation result with tasks and analysis
     */
    public async generateTasks(
        stories: string | object[],
        pages: string | object[]
    ): Promise<TaskGenerationResult> {
        const storiesJson = typeof stories === 'string' ? stories : JSON.stringify(stories, null, 2);
        const pagesJson = typeof pages === 'string' ? pages : JSON.stringify(pages, null, 2);

        const prompt = TASK_GENERATION_PROMPT(storiesJson, pagesJson);

        const response = await this.executePrompt(prompt);
        return this.parseTasksFromResponse(response);
    }

    /**
     * Generate a comprehensive steering document
     *
     * @param projectDescription - Project description
     * @param features - Features (JSON string or object array)
     * @param pages - Pages (JSON string or object array)
     * @param tasks - Tasks (JSON string or object array)
     * @returns Steering document result with recommendations
     */
    public async generateSteeringDocument(
        projectDescription: string,
        features: string | object[],
        pages: string | object[],
        tasks: string | object[]
    ): Promise<SteeringDocumentResult> {
        const featuresJson = typeof features === 'string' ? features : JSON.stringify(features, null, 2);
        const pagesJson = typeof pages === 'string' ? pages : JSON.stringify(pages, null, 2);
        const tasksJson = typeof tasks === 'string' ? tasks : JSON.stringify(tasks, null, 2);

        const prompt = STEERING_DOCUMENT_PROMPT(projectDescription, featuresJson, pagesJson, tasksJson);

        const response = await this.executePrompt(prompt);
        return this.parseSteeringDocumentFromResponse(response);
    }

    /**
     * Analyze task dependencies and suggest parallelization
     *
     * @param tasks - Tasks to analyze
     * @returns Dependency analysis with critical path and parallelization suggestions
     */
    public async analyzeDependencies(tasks: ArchitectTask[]): Promise<{
        criticalPath: string[];
        parallelGroups: string[][];
        bottlenecks: string[];
    }> {
        const prompt = `Analyze these tasks for dependencies and optimization:

${JSON.stringify(tasks, null, 2)}

Provide:
1. Critical path (the longest chain of dependent tasks)
2. Tasks that can be parallelized (groups of independent tasks)
3. Bottlenecks (tasks that many others depend on)

Output as JSON:
{
  "criticalPath": ["task-id-1", "task-id-2", ...],
  "parallelGroups": [["task-a", "task-b"], ["task-c", "task-d"]],
  "bottlenecks": ["task-id-that-blocks-many"]
}`;

        const response = await this.executePrompt(prompt);

        try {
            const jsonMatch = response.match(/```json\s*([\s\S]*?)```/);
            if (jsonMatch) {
                return JSON.parse(jsonMatch[1]);
            }
            return JSON.parse(response);
        } catch {
            return {
                criticalPath: [],
                parallelGroups: [],
                bottlenecks: [],
            };
        }
    }

    /**
     * Recommend technology stack based on project requirements
     *
     * @param requirements - Project requirements and constraints
     * @returns Technology stack recommendations
     */
    public async recommendTechStack(requirements: string): Promise<{
        recommendations: SteeringDocument['techStack'];
        rationale: Record<string, string>;
        alternatives: Record<string, string[]>;
    }> {
        const prompt = `Based on these requirements, recommend a technology stack:

${requirements}

Consider:
- Team expertise and learning curve
- Community support and ecosystem maturity
- Performance requirements
- Scalability needs
- Time to market constraints

Output as JSON:
{
  "recommendations": {
    "framework": "...",
    "language": "...",
    "styling": "...",
    "stateManagement": "...",
    "keyLibraries": [...]
  },
  "rationale": {
    "framework": "Why this framework",
    "language": "Why this language",
    ...
  },
  "alternatives": {
    "framework": ["alternative1", "alternative2"],
    ...
  }
}`;

        const response = await this.executePrompt(prompt);

        try {
            const jsonMatch = response.match(/```json\s*([\s\S]*?)```/);
            if (jsonMatch) {
                return JSON.parse(jsonMatch[1]);
            }
            return JSON.parse(response);
        } catch {
            return {
                recommendations: {
                    framework: 'React',
                    language: 'TypeScript',
                    styling: 'TailwindCSS',
                    stateManagement: 'React Context',
                    keyLibraries: ['React Router', 'React Query'],
                },
                rationale: {},
                alternatives: {},
            };
        }
    }

    /**
     * Get architecture best practices
     */
    public getArchitecturePrinciples(): string[] {
        return [
            'Single Responsibility Principle',
            'Separation of Concerns',
            'DRY (Don\'t Repeat Yourself)',
            'KISS (Keep It Simple, Stupid)',
            'YAGNI (You Aren\'t Gonna Need It)',
            'Defense in Depth',
            'Fail Fast',
            'Design for Testability',
            'Progressive Enhancement',
            'Graceful Degradation',
        ];
    }

    /**
     * Execute a prompt and get the response
     */
    private async executePrompt(prompt: string): Promise<string> {
        let result = '';
        const originalOnUpdate = this.onDidUpdateMessages;

        (this as any).onDidUpdateMessages = (messages: any[]) => {
            originalOnUpdate(messages);
            const lastMessage = messages[messages.length - 1];
            if (lastMessage?.role === 'model') {
                result = lastMessage.text;
            }
        };

        await this.chat(prompt, [], {}, undefined, false);
        (this as any).onDidUpdateMessages = originalOnUpdate;

        return result;
    }

    /**
     * Parse tasks from LLM response
     */
    private parseTasksFromResponse(response: string): TaskGenerationResult {
        try {
            const jsonMatch = response.match(/```json\s*([\s\S]*?)```/);
            const parsed = jsonMatch ? JSON.parse(jsonMatch[1]) : JSON.parse(response);

            const tasks: ArchitectTask[] = parsed.tasks || [];

            // Calculate total hours
            const totalEstimatedHours = tasks.reduce((sum, task) => sum + (task.estimatedHours || 0), 0);

            // Calculate critical path (longest dependency chain)
            const criticalPath = this.calculateCriticalPath(tasks);

            // Suggest parallelization
            const suggestedParallelization = this.suggestParallelization(tasks);

            return {
                tasks,
                totalEstimatedHours,
                criticalPath,
                suggestedParallelization,
            };
        } catch {
            return {
                tasks: [],
                totalEstimatedHours: 0,
                criticalPath: [],
                suggestedParallelization: [],
            };
        }
    }

    /**
     * Calculate critical path through tasks
     */
    private calculateCriticalPath(tasks: ArchitectTask[]): string[] {
        const taskMap = new Map(tasks.map(t => [t.id, t]));
        const depths = new Map<string, number>();

        const getDepth = (taskId: string, visited: Set<string> = new Set()): number => {
            if (depths.has(taskId)) return depths.get(taskId)!;
            if (visited.has(taskId)) return 0; // Cycle detected

            visited.add(taskId);
            const task = taskMap.get(taskId);
            if (!task || task.dependencies.length === 0) {
                depths.set(taskId, 1);
                return 1;
            }

            const maxDepDepth = Math.max(
                ...task.dependencies.map(depId => getDepth(depId, new Set(visited)))
            );
            const depth = maxDepDepth + 1;
            depths.set(taskId, depth);
            return depth;
        };

        // Calculate depths for all tasks
        tasks.forEach(t => getDepth(t.id));

        // Find the task with maximum depth (end of critical path)
        let maxDepth = 0;
        let criticalEnd = '';
        for (const [taskId, depth] of depths.entries()) {
            if (depth > maxDepth) {
                maxDepth = depth;
                criticalEnd = taskId;
            }
        }

        // Trace back the critical path
        const criticalPath: string[] = [];
        let current = criticalEnd;
        while (current) {
            criticalPath.unshift(current);
            const task = taskMap.get(current);
            if (!task || task.dependencies.length === 0) break;

            // Find the dependency with highest depth
            let maxDepDepth = 0;
            let nextTask = '';
            for (const depId of task.dependencies) {
                const depDepth = depths.get(depId) || 0;
                if (depDepth > maxDepDepth) {
                    maxDepDepth = depDepth;
                    nextTask = depId;
                }
            }
            current = nextTask;
        }

        return criticalPath;
    }

    /**
     * Suggest task parallelization
     */
    private suggestParallelization(tasks: ArchitectTask[]): string[][] {
        // Group tasks by their dependency level
        const levels = new Map<number, string[]>();
        const taskMap = new Map(tasks.map(t => [t.id, t]));

        const getLevel = (taskId: string, visited: Set<string> = new Set()): number => {
            if (visited.has(taskId)) return 0;
            visited.add(taskId);

            const task = taskMap.get(taskId);
            if (!task || task.dependencies.length === 0) return 0;

            return 1 + Math.max(...task.dependencies.map(d => getLevel(d, new Set(visited))));
        };

        for (const task of tasks) {
            const level = getLevel(task.id);
            if (!levels.has(level)) levels.set(level, []);
            levels.get(level)!.push(task.id);
        }

        // Return groups of 2+ tasks that can run in parallel
        return Array.from(levels.values()).filter(group => group.length >= 2);
    }

    /**
     * Parse steering document from LLM response
     */
    private parseSteeringDocumentFromResponse(response: string): SteeringDocumentResult {
        try {
            const jsonMatch = response.match(/```json\s*([\s\S]*?)```/);
            const parsed = jsonMatch ? JSON.parse(jsonMatch[1]) : JSON.parse(response);

            const document: SteeringDocument = parsed.steeringDocument || this.getDefaultSteeringDocument();

            // Generate recommendations based on document
            const recommendations = this.generateRecommendations(document);

            // Generate warnings for potential issues
            const warnings = this.generateWarnings(document);

            return {
                document,
                recommendations,
                warnings,
            };
        } catch {
            return {
                document: this.getDefaultSteeringDocument(),
                recommendations: ['Unable to generate custom recommendations'],
                warnings: ['Failed to parse steering document response'],
            };
        }
    }

    /**
     * Get default steering document
     */
    private getDefaultSteeringDocument(): SteeringDocument {
        return {
            projectOverview: {
                name: 'Project',
                description: '',
                targetUsers: [],
                coreValueProposition: '',
            },
            techStack: {
                framework: 'React',
                language: 'TypeScript',
                styling: 'TailwindCSS',
                stateManagement: 'React Context',
                keyLibraries: [],
            },
            codingStandards: {
                namingConventions: {
                    components: 'PascalCase',
                    functions: 'camelCase',
                    files: 'kebab-case',
                },
                fileOrganization: 'Feature-based',
                codeStyle: 'ESLint + Prettier',
            },
            architecturalPatterns: {
                componentArchitecture: 'Atomic Design',
                stateManagement: 'Context + Reducers',
                dataFlow: 'Unidirectional',
            },
            qualityRequirements: {
                testingStrategy: 'Unit + Integration',
                accessibilityStandards: 'WCAG 2.1 AA',
                performanceTargets: {
                    firstContentfulPaint: '<1.5s',
                    largestContentfulPaint: '<2.5s',
                },
            },
            constraints: {
                budgetConsiderations: 'Standard',
                timelineConstraints: 'Flexible',
                technicalConstraints: [],
            },
        };
    }

    /**
     * Generate recommendations based on steering document
     */
    private generateRecommendations(document: SteeringDocument): string[] {
        const recommendations: string[] = [];

        // Framework-specific recommendations
        if (document.techStack.framework === 'React') {
            recommendations.push('Consider using React Query for server state management');
            recommendations.push('Use React.memo for performance optimization of pure components');
        }

        // Testing recommendations
        if (document.qualityRequirements.testingStrategy.includes('Unit')) {
            recommendations.push('Target 80%+ code coverage for critical paths');
        }

        // Accessibility recommendations
        if (document.qualityRequirements.accessibilityStandards.includes('WCAG')) {
            recommendations.push('Implement semantic HTML and ARIA labels throughout');
            recommendations.push('Test with screen readers (NVDA, VoiceOver) during development');
        }

        return recommendations;
    }

    /**
     * Generate warnings for potential issues
     */
    private generateWarnings(document: SteeringDocument): string[] {
        const warnings: string[] = [];

        // Performance warnings
        if (!document.qualityRequirements.performanceTargets.firstContentfulPaint) {
            warnings.push('No performance targets defined - consider setting FCP and LCP goals');
        }

        // Constraint warnings
        if (document.constraints.technicalConstraints.length === 0) {
            warnings.push('No technical constraints defined - verify this is intentional');
        }

        return warnings;
    }
}
