/**
 * ArchitectAgent - Technical architecture and planning agent
 *
 * Handles:
 * - Task list generation from stories and pages
 * - Steering document creation with tech stack, coding standards, etc.
 * - Technical strategy recommendations
 *
 * Uses lower temperature (0.3-0.4) for consistent, deterministic output.
 *
 * **Part of Build-to-Design Transformation**
 * Validates: Requirements 9.1-9.9, 16.3
 */

import { BaseAgent, BaseAgentConfig } from '../base/BaseAgent';
import { AGENT_CAPABILITIES, AgentCapability } from '../base/AgentCapabilities';
import {
    TASK_GENERATION_PROMPT,
    STEERING_DOCUMENT_PROMPT,
} from '../../prompts/DesignPrompts';

// ============================================================================
// TYPES
// ============================================================================

/**
 * Task generated by the ArchitectAgent
 */
export interface ArchitectTask {
    id: string;
    title: string;
    description: string;
    storyId: string;
    pageId?: string;
    priority: 'P0' | 'P1' | 'P2';
    complexity: 'low' | 'medium' | 'high';
    estimatedHours: number;
    dependencies: string[];
    acceptanceCriteria: string[];
    technicalNotes?: string;
    category: 'frontend' | 'backend' | 'database' | 'integration' | 'testing';
    isUserModified: boolean;
}

/**
 * Steering document sections
 */
export interface SteeringDocument {
    projectOverview: {
        name: string;
        description: string;
        targetUsers: string[];
        coreValueProposition: string;
    };
    techStack: {
        framework: string;
        language: string;
        styling: string;
        stateManagement: string;
        keyLibraries: string[];
    };
    codingStandards: {
        namingConventions: {
            components: string;
            functions: string;
            files: string;
        };
        fileOrganization: string;
        codeStyle: string;
    };
    architecturalPatterns: {
        componentArchitecture: string;
        stateManagement: string;
        dataFlow: string;
    };
    qualityRequirements: {
        testingStrategy: string;
        accessibilityStandards: string;
        performanceTargets: {
            firstContentfulPaint: string;
            largestContentfulPaint: string;
        };
    };
    constraints: {
        budgetConsiderations: string;
        timelineConstraints: string;
        technicalConstraints: string[];
    };
}

/**
 * Options for ArchitectAgent creation
 */
export interface ArchitectAgentOptions {
    /** Temperature for LLM (default: 0.3 for consistent output) */
    temperature?: number;
    /** Project context for better recommendations */
    projectContext?: string;
}

/**
 * Result from task generation
 */
export interface TaskGenerationResult {
    tasks: ArchitectTask[];
    totalEstimatedHours: number;
    criticalPath: string[];
    suggestedParallelization: string[][];
}

/**
 * Result from steering document generation
 */
export interface SteeringDocumentResult {
    document: SteeringDocument;
    recommendations: string[];
    warnings: string[];
}

